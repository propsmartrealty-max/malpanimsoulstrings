/**
 * Generates all valid slug permutations for programmatic landing pages
 */
export function getAllProgrammaticSlugs() {
  const slugs = [];

  // 1. Property Type + Location (e.g. 3-bhk-luxury-apartments-baner-pashan-link-road)
  propertyTypes.forEach(prop => {
    locations.forEach(loc => {
      slugs.push(`${prop.slugPart}-${loc.slugPart}`);
    });
  });

  // 2. Property Type + Intent + Core Markets
  intents.forEach(intent => {
    propertyTypes.forEach(prop => {
      slugs.push(`${intent.slugPart}-${prop.slugPart}-baner`);
      slugs.push(`${intent.slugPart}-${prop.slugPart}-pune-west`);
      slugs.push(`${intent.slugPart}-${prop.slugPart}-hinjewadi`);
    });
  });

  // 3. Location + Intent (e.g. vastu-compliant-luxury-homes-near-koregaon-park-pune)
  locations.forEach(loc => {
    intents.forEach(intent => {
      slugs.push(`${intent.slugPart}-luxury-homes-${loc.slugPart}`);
    });
  });

  // Deduplicate
  return Array.from(new Set(slugs));
}
