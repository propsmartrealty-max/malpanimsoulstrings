/**
 * Generates all valid slug permutations for programmatic landing pages.
 * Pre-renders the highest-intent matrix for initial SSG build, while
 * dynamicParams = true handles the full 10,000+ long-tail permutations on-demand with ISR.
 */
export function getAllProgrammaticSlugs() {
  const slugs = [];

  // 1. Property Type + Location (e.g. 3-bhk-luxury-apartments-baner-pashan-link-road)
  propertyTypes.forEach(prop => {
    locations.forEach(loc => {
      slugs.push(`${prop.slugPart}-${loc.slugPart}`);
    });
  });

  // 2. High-Intent + Property Type + Core Micro-Markets
  const coreMarkets = ['baner-pashan-link-road', 'baner-pune', 'near-hinjewadi-phase-1', 'near-balewadi-high-street', 'near-aundh-pune', 'near-wakad-pune', 'pune-west', 'near-koregaon-park-pune', 'near-kharadi-it-hub-pune'];
  
  intents.forEach(intent => {
    propertyTypes.forEach(prop => {
      coreMarkets.forEach(market => {
        slugs.push(`${intent.slugPart}-${prop.slugPart}-${market}`);
      });
    });
  });

  // 3. Location + Intent (e.g. vastu-compliant-luxury-homes-near-balewadi-high-street)
  locations.forEach(loc => {
    intents.forEach(intent => {
      slugs.push(`${intent.slugPart}-luxury-homes-${loc.slugPart}`);
    });
  });

  // Deduplicate
  return Array.from(new Set(slugs));
}
